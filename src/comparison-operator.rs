/* Comparison Operator
 * - Greater than " > "
 * - Less than " < "
 * - Greater than equal " >= "
 * - Less than equal " <= "
 * - Equal " == "
 */

fn main(){
    let check1: bool =  1 > 2;
    println!("check1 = {}", check1);
    let check2: bool = 1 < 2;
    println!("check2 = {}", check2);
    let check3: bool = 1 >= 2;
    println!("check3 = {}", check3);
    let check4: bool = 1 <= 2;
    println!("check4 = {}", check4);
}
